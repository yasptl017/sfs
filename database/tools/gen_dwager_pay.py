"""
Generator for the two D.Wager pay registers (sheets 'D.Wager Salary' and 'D.Wager Arrears'):
reads the staged sheets of the 14 office workbooks of 2025-26 (Division + 13 ranges) and of the Division workbook of 2026-27,
infers a column type from ALL cells (numeric -> decimal, date -> date, anything mixed -> text) and writes
  database/migration/dwager_pay_spec.json   and   database/migrations/2026_11_28_000038_create_d_wager_pay_tables.php
    python -I -X utf8 database/tools/gen_dwager_pay.py
"""
import collections
import json
import os
import re

import pymysql

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def env(path):
    out = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^([A-Z_]+)=(.*)$", line.strip())
        if m:
            out[m.group(1)] = m.group(2).strip('"')
    return out


E = env(os.path.join(ROOT, ".env"))
db = pymysql.connect(host=E["DB_HOST"], port=int(E["DB_PORT"]), user=E["DB_USERNAME"], password=E["DB_PASSWORD"], database=E["DB_DATABASE"], charset="utf8mb4")
cur = db.cursor()
RANGES = ["Bayad", "Bhiloda", "Dhansura", "Himatnagar", "Idar", "Khedbrahma", "Malpur", "Meghraj", "Modasa", "Prantij", "Talod", "Vadali", "Vijaynagar"]
SOURCES = {"2025-26": ["DIvision Range Fin. System/Division SFS 25-26 RFS.xlsx"] + [f"Range Finance System/{r} SFS 25-26 RFS.xlsx" for r in RANGES],
           "2026-27": ["Division SFS 26-27 RFS.xlsx"]}
SHEETS = {"d_wager_salaries": ("D.Wager Salary", 0), "d_wager_arrears": ("D.Wager Arrears", 1)}   # (sheet name, header row index)
RENAME = {"Sr.": "serial_number", "D.Wager Code": "d_wager_code", "D.Wager Name": "d_wager_name", "Arears Description": "arrears_description"}


def slug(h):
    h = h.replace("%", "percent")
    return re.sub(r"[^a-z0-9]+", "_", h.lower()).strip("_")


def staged(src, name):
    cur.execute("SELECT id FROM staging_sheets WHERE source_file=%s AND sheet_name=%s", (src, name))
    sid = cur.fetchone()[0]
    cur.execute("SELECT row_no, cells FROM staging_rows WHERE staging_sheet_id=%s ORDER BY row_no", (sid,))
    return [(r, json.loads(c)) for r, c in cur.fetchall()]


spec = {}
for table, (sheet, hrow) in SHEETS.items():
    headers = None
    types = collections.defaultdict(set)
    maxlen = collections.Counter()
    nrows = 0
    for fy, files in SOURCES.items():
        for f in files:
            rows = staged(f, sheet)
            h = rows[hrow][1]
            if headers is None:
                headers = h
            assert h == headers or [x for x in h if x] == [x for x in headers if x], (f, sheet)
            for r, c in rows[hrow + 1:]:
                if not any(v is not None for v in c):
                    continue
                nrows += 1
                for i, v in enumerate(c):
                    if v is None:
                        continue
                    if isinstance(v, str) and v.strip().lower() == "unlocked" and i >= len(headers):
                        continue
                    t = "num" if isinstance(v, (int, float)) and not isinstance(v, bool) else ("date" if isinstance(v, str) and re.match(r"^\d{4}-\d{2}-\d{2}", v) else "text")
                    types[i].add(t)
                    maxlen[i] = max(maxlen[i], len(str(v)))
    cols = []
    for i, hname in enumerate(headers):
        if hname is None:
            continue
        t = types[i]
        kind = "dec" if t == {"num"} else ("date" if t == {"date"} else ("text" if t else "text"))
        if t == {"num"} and hname in ("Sr.", "Salary Year", "Pay Year"):
            kind = "int"
        cols.append({"idx": i, "header": hname, "name": RENAME.get(hname) or slug(hname), "kind": kind, "maxlen": maxlen[i]})
    names = [c["name"] for c in cols]
    assert len(set(names)) == len(names), names
    spec[table] = {"sheet": sheet, "header_row": hrow, "columns": cols, "sources": SOURCES, "rows_seen": nrows}
    print(table, nrows, "rows;", collections.Counter(c["kind"] for c in cols))

json.dump(spec, open(os.path.join(ROOT, "database", "migration", "dwager_pay_spec.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

lines = ["<?php", "", "use Illuminate\\Database\\Migrations\\Migration;", "use Illuminate\\Database\\Schema\\Blueprint;", "use Illuminate\\Support\\Facades\\Schema;", "",
         "/**", " * D.Wager pay registers (sheets 'D.Wager Salary' and 'D.Wager Arrears' of the Division / range workbooks): the monthly salary and", " * the arrears calculation of every daily-wager - working days, leaves, basic pay, D.A., H.R.A., deductions, net. Generated by",
         " * database/tools/gen_dwager_pay.py from the real sheets (mixed columns are kept as text). Re-runnable.", " */", "return new class extends Migration", "{", "    public function up(): void", "    {"]
for table, s in spec.items():
    lines += [f"        if (! Schema::hasTable('{table}')) {{", f"            Schema::create('{table}', function (Blueprint $t) {{", "                $t->id();",
              "                $t->foreignId('financial_year_id')->constrained('financial_years')->restrictOnDelete();",
              "                $t->foreignId('range_id')->constrained('users')->restrictOnDelete();", "                $t->string('range_name')->nullable();"]
    for c in s["columns"]:
        n = c["name"]
        if c["kind"] == "int":
            lines.append(f"                $t->unsignedInteger('{n}')->nullable();")
        elif c["kind"] == "dec":
            lines.append(f"                $t->decimal('{n}', 20, 4)->nullable();")
        elif c["kind"] == "date":
            lines.append(f"                $t->date('{n}')->nullable();")
        else:
            lines.append(f"                $t->text('{n}')->nullable();")
    lines += ["                $t->foreignId('staging_sheet_id')->nullable()->constrained('staging_sheets')->nullOnDelete();", "                $t->unsignedInteger('source_row')->nullable();",
              "                $t->timestamps();", f"                $t->index(['financial_year_id', 'range_id'], '{table[:20]}_fy_range');", "            });", "        }"]
lines += ["    }", "", "    public function down(): void", "    {"]
for table in spec:
    lines.append(f"        Schema::dropIfExists('{table}');")
lines += ["    }", "};", ""]
open(os.path.join(ROOT, "database", "migrations", "2026_11_28_000038_create_d_wager_pay_tables.php"), "w", encoding="utf-8").write("\n".join(lines))
print("written spec + migration")
